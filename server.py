def _file_sha256(path):
    with Path(path).open('rb') as source:
        return hashlib.file_digest(source, 'sha256').hexdigest()


def _overlay_path(root, name):
    path = Path(name)
    if (not name or path.is_absolute() or '\\' in name
            or any(part.startswith('.') for part in path.parts)):
        raise ValueError('Unsafe overlay path')
    target = root.joinpath(*path.parts)
    target.resolve().relative_to(root.resolve())
    return target


def _apply_overlay(stage, payload):
    if hashlib.sha256(payload).hexdigest() != _OVERLAY_SHA256:
        raise ValueError('Chart overlay checksum mismatch')
    seen = set()
    with tarfile.open(fileobj=io.BytesIO(payload), mode='r:gz') as archive:
        for member in archive:
            name = member.name
            if (not member.isfile() or name not in _OVERLAY_FILES
                    or name in seen or member.size != _OVERLAY_FILES[name]['size']):
                raise ValueError('Unsafe or unexpected chart overlay entry')
            target = _overlay_path(stage, name)
            with archive.extractfile(member) as source:
                content = source.read(member.size + 1)
            if (len(content) != member.size
                    or hashlib.sha256(content).hexdigest() != _OVERLAY_FILES[name]['sha256']):
                raise ValueError('Chart overlay file checksum mismatch')
            # Every allowed overlay file is reviewed UTF-8 source or metadata.
            content.decode('utf-8', errors='strict')
            target.parent.mkdir(parents=True, exist_ok=True)
            if target.is_symlink():
                raise ValueError('Symbolic link in chart overlay target')
            target.write_bytes(content)
            target.chmod(0o644)
            seen.add(name)
    if seen != set(_OVERLAY_FILES):
        raise ValueError('Incomplete chart overlay')
    for name in _OVERLAY_REMOVALS:
        target = _overlay_path(stage, name)
        if target.is_symlink():
            raise ValueError('Symbolic link in chart removal target')
        if target.exists():
            if not target.is_file():
                raise ValueError('Chart removal target is not a file')
            target.unlink()
    runpy.run_path(str(stage / 'scripts/refresh_source_archive.py'), run_name='__main__')
    for name, expected in (
        ('roots-and-sky-source.zip', _SOURCE_ZIP_SHA256),
        ('roots-and-sky-runtime.zip', _RUNTIME_ZIP_SHA256),
    ):
        if _file_sha256(stage / 'dist/source' / name) != expected:
            raise ValueError('Chart source download checksum mismatch')
    for name in _OVERLAY_REMOVALS:
        if _overlay_path(stage, name).exists():
            raise ValueError('Obsolete report asset remains in chart staging')


@contextmanager
def prepare_static_root(original=ROOT):
    """Serve an isolated chart-only copy; never write into the image's dist/."""
    original = Path(original).resolve()
    if not (original / 'index.html').is_file():
        raise ValueError('Missing original static payload')
    if any(path.is_symlink() for path in original.rglob('*')):
        raise ValueError('Symbolic link in original static payload')
    payload = base64.b64decode(''.join(_OVERLAY_B64.split()), validate=True)
    with tempfile.TemporaryDirectory(prefix='roots-sky-chart-') as temporary:
        stage = Path(temporary)
        shutil.copytree(original, stage / 'dist')
        _apply_overlay(stage, payload)
        yield stage / 'dist'


class StaticHandler(BaseHTTPRequestHandler):
    server_version = 'RootsSky'
    sys_version = ''

    def log_message(self, *_args):
        # No request logs: the app has no server-side visitor or report store.
        pass

    def end_headers(self):
        self.send_header('X-Content-Type-Options', 'nosniff')
        self.send_header('Referrer-Policy', 'no-referrer')
        self.send_header('X-Frame-Options', 'SAMEORIGIN')
        super().end_headers()

    def do_GET(self):
        self.serve(head=False)

    def do_HEAD(self):
        self.serve(head=True)

    def do_POST(self):
        self.send_error(405, 'Read-only static service')

    do_PUT = do_DELETE = do_PATCH = do_POST

    def serve(self, head=False):
        try:
            path = unquote(urlsplit(self.path).path, errors='strict')
            if not path.startswith('/') or '\\' in path or '%' in path or '\x00' in path:
                raise ValueError('Invalid path')
            parts = [part for part in path.split('/') if part]
            if any(part.startswith('.') for part in parts):
                raise ValueError('Private path')
            root = Path(self.server.document_root).resolve()
            target = root.joinpath(*parts)
            cursor = root
            for part in parts:
                cursor = cursor / part
                if cursor.is_symlink():
                    raise ValueError('Symbolic link')
            target.resolve().relative_to(root)
            if target.is_dir():
                if not path.endswith('/'):
                    # Relative resource paths in directory index pages need a trailing slash.
                    self.send_response(308)
                    self.send_header('Location', path + '/')
                    self.send_header('Content-Length', '0')
                    self.send_header('Cache-Control', 'no-cache')
                    self.end_headers()
                    return
                target = target / 'index.html'
            if not target.is_file() or target.is_symlink():
                raise ValueError('Missing file')
        except (ValueError, UnicodeError, OSError):
            self.send_error(404, 'File not found')
            return
        try:
            stat = target.stat()
            key = (str(target), stat.st_size, stat.st_mtime_ns)
            etag = self.server.etags.get(key)
            if etag is None:
                with target.open('rb') as source:
                    etag = '"' + hashlib.file_digest(source, 'sha256').hexdigest() + '"'
                self.server.etags[key] = etag
            if self.headers.get('If-None-Match') == etag:
                self.send_response(304)
                self.send_header('ETag', etag)
                self.send_header('Cache-Control', 'public, max-age=0, must-revalidate')
                self.end_headers()
                return
            with target.open('rb') as source:
                self.send_response(200)
                self.send_header('Content-Type', MIME.get(target.suffix.lower(), mimetypes.guess_type(target.name)[0] or 'application/octet-stream'))
                self.send_header('Content-Length', str(stat.st_size))
                self.send_header('Cache-Control', 'public, max-age=0, must-revalidate')
                self.send_header('ETag', etag)
                self.end_headers()
                if not head:
                    shutil.copyfileobj(source, self.wfile, 64 * 1024)
        except (BrokenPipeError, ConnectionResetError):
            pass


def make_server(host='0.0.0.0', port=8080, root=ROOT):
    server = ThreadingHTTPServer((host, port), StaticHandler)
    server.daemon_threads = True
    server.document_root = Path(root).resolve()
    server.etags = {}
    return server


if __name__ == '__main__':
    port = int(os.environ.get('PORT', '8080'))
    if not 1 <= port <= 65535:
        raise SystemExit('PORT must be between 1 and 65535')
    if not (ROOT / 'index.html').is_file():
        raise SystemExit('Missing dist/index.html; reconstruct the payload first')
    with prepare_static_root(ROOT) as staged_root:
        make_server(port=port, root=staged_root).serve_forever()
